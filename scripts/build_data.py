#!/usr/bin/env python3
"""Generate docs/data.js from README.md (the single source of truth).

Run from anywhere:  python3 scripts/build_data.py
The GitHub workflow .github/workflows/sync-site-data.yml runs this on every
push to main that touches README.md and commits the result, so the Atlas
site never drifts from the list.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
OUT = ROOT / "docs" / "data.js"

# Local entries whose names don't end in ", Country" and need an explicit home.
COUNTRY_OVERRIDES = {
    "Bristol City Council": "United Kingdom",
    "Camden": "United Kingdom",
    "Croydon": "United Kingdom",
    "Hackney": "United Kingdom",
    "Redbridge": "United Kingdom",
    "Southwark": "United Kingdom",
    "Transport for West Midlands": "United Kingdom",
    "New York City": "United States",
}

def clean(s):
    return re.sub(r"\*\*(.+?)\*\*", r"\1", s).strip()

def marker(s):
    for m in ["🟢", "🟡", "🔴"]:
        if m in s:
            return m
    return None

def derive_country(e):
    if e["name"] in COUNTRY_OVERRIDES:
        return COUNTRY_OVERRIDES[e["name"]]
    if e["level"] == "Local / Municipal":
        return e["name"].split(",")[-1].strip()
    return e["name"].split(" - ")[0].strip()

def parse(text):
    lines = text.split("\n")
    entries, section, i = [], None, 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("## "):
            section = l[3:].strip(); i += 1; continue
        m = re.match(r"^#{3,4} \[([^\]]+)\]\(([^)]+)\)", l)
        if m and section:
            name, url = m.group(1), m.group(2)
            rows, j = [], i + 1
            while j < len(lines) and not re.match(r"^#{2,4} ", lines[j]):
                if lines[j].startswith("|") and "---" not in lines[j] and "**Feature**" not in lines[j]:
                    cells = [c.strip() for c in lines[j].strip().strip("|").split("|")]
                    if len(cells) >= 3:
                        rows.append(cells)
                j += 1
            e = {"name": name, "url": url, "level": section, "source": None,
                 "status": "", "info": "", "tech": "", "techInfo": "",
                 "webComponents": None, "wcag": None, "wcagInfo": "",
                 "tools": None, "toolsInfo": ""}
            for r in rows:
                label = clean(r[0])
                lm = re.match(r"\[([^\]]+)\]\(([^)]+)\)", r[0])
                if lm and "Source Code" in lm.group(1):
                    e["source"] = lm.group(2); e["status"] = clean(r[1]); e["info"] = clean(r[2])
                elif label == "No Public Source Code Found":
                    e["status"] = clean(r[1]); e["info"] = clean(r[2])
                elif label.startswith("Underpinning Technology"):
                    e["tech"] = clean(r[1]); e["techInfo"] = clean(r[2])
                elif label.startswith("Web Components"):
                    e["webComponents"] = marker(r[1])
                elif label.startswith("508 Compliant"):
                    e["wcag"] = marker(r[1]); e["wcagInfo"] = clean(r[2])
                elif label.startswith("Storybook"):
                    e["tools"] = marker(r[1]); e["toolsInfo"] = clean(r[2])
            e["country"] = derive_country(e)
            entries.append(e)
            i = j; continue
        i += 1
    return entries

def main():
    entries = parse(README.read_text(encoding="utf-8"))
    stats = {
        "total": len(entries),
        "countries": len({e["country"] for e in entries}),
        "withSource": sum(1 for e in entries if e["source"]),
        "wcagGreen": sum(1 for e in entries if e["wcag"] == "🟢"),
        "toolsGreen": sum(1 for e in entries if e["tools"] == "🟢"),
        "wcGreen": sum(1 for e in entries if e["webComponents"] == "🟢"),
    }
    payload = ("// Generated by scripts/build_data.py from README.md — do not edit by hand.\n"
               "window.DS_DATA=" + json.dumps(entries, ensure_ascii=False) + ";\n"
               "window.DS_STATS=" + json.dumps(stats, ensure_ascii=False) + ";\n")
    OUT.write_text(payload, encoding="utf-8")
    print(f"Wrote {OUT} — {stats}")

if __name__ == "__main__":
    main()
